BEGIN;
DO $$
DECLARE c RECORD; buyer UUID; seller UUID; r UUID; item UUID; v UUID; g UUID; payload JSONB; allocation JSONB; result JSONB; original_stock INTEGER; before_orders INTEGER; rejected BOOLEAN;
BEGIN
 SELECT * INTO c FROM zz.cc LIMIT 1;
 SELECT owner_id INTO buyer FROM public.businesses WHERE id=c.good;
 SELECT owner_id INTO seller FROM public.businesses WHERE id=c.alpha;
 PERFORM set_config('request.jwt.claim.sub',buyer::text,true);
 r:=public.save_enterprise_rfq(c.good,jsonb_build_object('title','Credit failure recovery','deadline',now()+interval '1 day','items',jsonb_build_array(jsonb_build_object('productName','Test medicine','quantity',10,'alternativesAllowed',true)),'suppliers',jsonb_build_array(c.alpha)),gen_random_uuid());
 PERFORM public.publish_enterprise_rfq(r,(SELECT revision FROM public.rfqs WHERE id=r));
 SELECT id INTO item FROM public.rfq_items WHERE rfq_id=r;
 PERFORM set_config('request.jwt.claim.sub',seller::text,true);
 payload:=jsonb_build_object('validUntil',now()+interval '2 days','items',jsonb_build_array(jsonb_build_object('rfqItemId',item,'productId',c.p_item_a,'quantity',10,'unitPriceGhs',50,'alternative',true,'expiryDate',current_date+800)));
 v:=public.save_enterprise_quote(r,c.alpha,payload,true,0,gen_random_uuid());
 PERFORM set_config('request.jwt.claim.sub',buyer::text,true);
 allocation:=jsonb_build_array(jsonb_build_object('versionId',v,'quoteItemId',(SELECT id FROM public.rfq_quote_items WHERE rfq_item_id=item),'quantity',10,'acceptAlternative',true,'category','cash_private'));
 UPDATE public.rfq_items SET partial_allowed=false WHERE id=item;
 rejected:=false;
 BEGIN PERFORM public.propose_rfq_awards(r,jsonb_build_array((allocation->0)||'{"quantity":5}'),'cod',gen_random_uuid());
 EXCEPTION WHEN raise_exception THEN
   IF SQLERRM NOT LIKE '%does not permit a partial award%' THEN RAISE; END IF;
   rejected:=true;
 END;
 IF NOT rejected THEN RAISE EXCEPTION 'All-or-nothing requirement allowed partial award'; END IF;
 rejected:=false; BEGIN PERFORM public.award_rfq_lines(r,allocation,false); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Legacy award bypass permitted'; END IF;
 rejected:=false; BEGIN PERFORM public.propose_rfq_awards(r,jsonb_build_array((allocation->0)||'{"acceptAlternative":false}'),'cod',gen_random_uuid()); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Alternative accepted without consent'; END IF;
 g:=(public.propose_rfq_awards(r,allocation,'credit',gen_random_uuid())->>0)::uuid;
 UPDATE public.wholesaler_credit_terms SET active=false WHERE wholesaler_id=c.alpha AND pharmacy_id=c.good;
 SELECT stock INTO original_stock FROM public.products WHERE id=c.p_item_a;
 SELECT count(*) INTO before_orders FROM public.orders;
 PERFORM set_config('request.jwt.claim.sub',seller::text,true);
 result:=public.confirm_rfq_award(g,true);
 IF result->>'status'<>'conversion_failed' THEN RAISE EXCEPTION 'Inactive credit was not blocked: %',result; END IF;
 IF (SELECT count(*) FROM public.orders)<>before_orders OR (SELECT stock FROM public.products WHERE id=c.p_item_a)<>original_stock THEN RAISE EXCEPTION 'Failed conversion left stock or order side effects'; END IF;
 rejected:=false; BEGIN PERFORM public.save_enterprise_quote(r,c.alpha,payload||'{"reason":"Change pending award"}',true,1,gen_random_uuid()); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Pending award terms could be revised'; END IF;
 PERFORM public.confirm_rfq_award(g,false,'Credit terms unavailable; please choose cash');
 PERFORM set_config('request.jwt.claim.sub',buyer::text,true);
 g:=(public.propose_rfq_awards(r,allocation,'cod',gen_random_uuid())->>0)::uuid;
 IF (SELECT status FROM public.rfq_confirmation_groups WHERE id=g)<>'pending' THEN RAISE EXCEPTION 'Decline did not release quantities'; END IF;
 PERFORM set_config('request.jwt.claim.sub',seller::text,true);
 result:=public.confirm_rfq_award(g,true);
 IF result->>'status'<>'confirmed' THEN RAISE EXCEPTION 'Cash retry failed: %',result; END IF;
 IF (SELECT stock FROM public.products WHERE id=c.p_item_a)<>original_stock-10 THEN RAISE EXCEPTION 'Cash retry stock wrong'; END IF;
 PERFORM set_config('request.jwt.claim.sub','10000000-0000-0000-0000-00000000000b',true);
 rejected:=false; BEGIN PERFORM public.rfq_document(r,v); EXCEPTION WHEN OTHERS THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Unrelated user could export quotation'; END IF;
 IF public.rfq_storage_access(r::text||'/'||c.alpha::text||'/test',true) THEN RAISE EXCEPTION 'Unrelated user could upload supplier evidence'; END IF;
 RAISE NOTICE 'PASS: legacy bypass, alternative consent, inactive credit, atomic failure, locked terms, decline release, cash recovery, document/storage access';
END $$;
ROLLBACK;
