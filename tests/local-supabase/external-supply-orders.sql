-- Isolated fixture database only; all test data rolls back.
BEGIN;
CREATE FUNCTION pg_temp.assert(ok boolean,label text) RETURNS void LANGUAGE plpgsql AS $$ BEGIN IF ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'FAIL: %',label; END IF; RAISE NOTICE 'PASS: %',label; END $$;
DO $$
DECLARE pharmacy uuid:=(SELECT id FROM businesses WHERE name='Good Pharmacy');
 outsider uuid:=(SELECT owner_id FROM businesses WHERE name='Pending Pharmacy');
 owner_uid uuid:=(SELECT owner_id FROM businesses WHERE id=pharmacy);
 oid uuid; rid uuid; receipt uuid; receipt2 uuid; req uuid:=gen_random_uuid(); line_id uuid:=gen_random_uuid(); data jsonb; payload jsonb; denied boolean; initial_stock numeric; frozen jsonb;
BEGIN
 SELECT COALESCE(sum(stock),0) INTO initial_stock FROM pharmacy_inventory_items WHERE pharmacy_id=pharmacy;
 PERFORM set_config('request.jwt.claim.sub',owner_uid::text,true);
 SET LOCAL ROLE authenticated;
 data:=jsonb_build_object('kind','request','supplier','Outside Supplier','lines',jsonb_build_array(jsonb_build_object('id',line_id,'name','Test medicine 500mg pack 10','quantity',20,'unit_price',NULL)));
 rid:=public.save_external_supply_order(pharmacy,data,req);
 PERFORM pg_temp.assert(public.save_external_supply_order(pharmacy,data,req)=rid,'Repeated request creates one draft');
 denied:=false; BEGIN PERFORM public.save_external_supply_order(pharmacy,jsonb_set(data,'{supplier}','"Different"'),req); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Different payload cannot reuse request key');
 PERFORM public.transition_external_supply_order(rid,1,'issued');
 SELECT issuer INTO frozen FROM public.external_supply_orders WHERE id=rid;
 PERFORM pg_temp.assert(frozen->>'name'='Good Pharmacy','Issuer identity captured at issue');
 denied:=false; BEGIN PERFORM public.save_external_supply_order(pharmacy,data,gen_random_uuid(),rid,2); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Issued request cannot be edited');
 denied:=false; BEGIN PERFORM public.transition_external_supply_order(rid,1,'shared'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Stale status transition rejected');
 PERFORM public.transition_external_supply_order(rid,2,'shared');
 data:=data||jsonb_build_object('kind','order','source_request_id',rid);
 oid:=public.save_external_supply_order(pharmacy,data,gen_random_uuid());
 denied:=false; BEGIN PERFORM public.transition_external_supply_order(oid,1,'issued'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Order requires prices before issue');
 data:=jsonb_set(data,'{lines,0,unit_price}','5');
 PERFORM public.save_external_supply_order(pharmacy,data,gen_random_uuid(),oid,1);
 PERFORM public.transition_external_supply_order(oid,2,'issued');
 PERFORM pg_temp.assert((SELECT COALESCE(sum(stock),0)=initial_stock FROM pharmacy_inventory_items WHERE pharmacy_id=pharmacy),'Requests and orders do not post stock');
 payload:=jsonb_build_object('external_order_id',oid,'purchase_date',current_date,'channel','unknown','source_type','unknown','source','{}'::jsonb,'items',jsonb_build_array(jsonb_build_object('external_order_line_id',line_id,'product',jsonb_build_object('name','Test medicine 500mg pack 10'),'quantity',12,'unit_cost_ghs',5,'batches',jsonb_build_array(jsonb_build_object('quantity',12)))));
 req:=gen_random_uuid(); receipt:=public.save_external_purchase(pharmacy,payload,req);
 PERFORM pg_temp.assert(public.save_external_purchase(pharmacy,payload,req)=receipt,'Receipt retry is idempotent');
 PERFORM pg_temp.assert((SELECT external_order_allocations#>>'{0,quantity}'='12' AND external_order_id=oid FROM external_purchases WHERE id=receipt),'Partial receipt linked to order');
 denied:=false; BEGIN PERFORM public.save_external_purchase(pharmacy,payload,gen_random_uuid()); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Over-receipt rejected');
 denied:=false; BEGIN PERFORM public.save_external_purchase(pharmacy,payload-'external_order_id',gen_random_uuid(),receipt,1); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Linked receipt cannot be detached');
 payload:=jsonb_set(jsonb_set(payload,'{items,0,quantity}','8'),'{items,0,batches,0,quantity}','8');
 receipt2:=public.save_external_purchase(pharmacy,payload,gen_random_uuid());
 PERFORM pg_temp.assert((SELECT sum((external_order_allocations#>>'{0,quantity}')::integer)=20 FROM external_purchases WHERE external_order_id=oid),'Multiple receipts fulfil exact ordered quantity');
 PERFORM pg_temp.assert((SELECT COALESCE(sum(stock),0)=initial_stock FROM pharmacy_inventory_items WHERE pharmacy_id=pharmacy),'Unreviewed receipts do not post stock');
 PERFORM public.transition_external_supply_order(oid,3,'cancelled');
 denied:=false; BEGIN PERFORM public.save_external_purchase(pharmacy,payload,gen_random_uuid()); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Cancelled order cannot receive new deliveries');
 PERFORM pg_temp.assert((SELECT count(*)>=3 FROM external_supply_order_events WHERE order_id=oid),'Document changes audited');
 denied:=false; BEGIN PERFORM public.save_external_purchase_before_orders(pharmacy,payload,gen_random_uuid()); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Old receipt function cannot bypass linkage guard');
 PERFORM set_config('request.jwt.claim.sub',outsider::text,true);
 PERFORM pg_temp.assert((SELECT count(*)=0 FROM external_supply_orders WHERE id=oid),'Unrelated user cannot read order');
 denied:=false; BEGIN PERFORM public.transition_external_supply_order(oid,4,'shared'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Unrelated user cannot change order');
 denied:=false; BEGIN PERFORM public.save_external_supply_order(pharmacy,data,gen_random_uuid()); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Unrelated user cannot create order');
 RESET ROLE;
END $$;
ROLLBACK;
