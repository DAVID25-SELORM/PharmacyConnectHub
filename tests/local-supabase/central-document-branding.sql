-- Isolated local fixture only. All mutations roll back.
BEGIN;
CREATE FUNCTION pg_temp.assert(ok boolean,label text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN IF ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'FAIL: %',label; END IF; RAISE NOTICE 'PASS: %',label; END $$;
DO $$
DECLARE a uuid:=(SELECT id FROM businesses WHERE name='Good Pharmacy');
 b uuid:=(SELECT id FROM businesses WHERE name='Alpha Wholesale');
 uid uuid:=(SELECT owner_id FROM businesses WHERE id=a);
 oid uuid; rid uuid; before_identity jsonb; denied boolean; path text;
 staff_uid uuid:=(SELECT owner_id FROM businesses WHERE name='Pending Pharmacy');
BEGIN
 PERFORM set_config('request.jwt.claim.sub',uid::text,true);
 SET LOCAL ROLE authenticated;
 PERFORM public.save_document_presentation(a,'Trading name',NULL,'#115544',true,true,'Original');
 PERFORM pg_temp.assert((SELECT footer_note='Original' FROM business_document_branding WHERE business_id=a),'Owner saves presentation');
 denied:=false;
 BEGIN PERFORM public.save_document_presentation(b,NULL,NULL,'#115544',true,true,NULL); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Cross-tenant save denied');
 denied:=false;
 BEGIN PERFORM public.save_business_document_branding(a,p_payment_instructions=>'Send money elsewhere'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Legacy RPC cannot modify payment instructions');
 denied:=false;
 BEGIN PERFORM public.save_document_presentation(a,NULL,NULL,'#115544',true,true,'<script>'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Markup rejected');
 denied:=false;
 BEGIN INSERT INTO storage.objects(bucket_id,name) VALUES('business-document-logos',a||'/bypass.png'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Direct upload cannot bypass validation');
 RESET ROLE;
 path:=a||'/validated.webp';
 INSERT INTO storage.objects(bucket_id,name) VALUES('business-document-logos',path);
 INSERT INTO document_branding_assets(path,business_id,uploaded_by,byte_size) VALUES(path,a,uid,100);
 SET LOCAL ROLE authenticated;
 PERFORM public.save_document_presentation(a,NULL,path,'#115544',true,true,'With logo');
 PERFORM pg_temp.assert((SELECT logo_path=path FROM business_document_branding WHERE business_id=a),'Validated own logo can be selected');
 PERFORM public.save_document_presentation(a,NULL,NULL,'#115544',true,true,'Removed logo');
 PERFORM pg_temp.assert((SELECT logo_path IS NULL FROM business_document_branding WHERE business_id=a),'Logo removal clears current reference');
 RESET ROLE;
 PERFORM pg_temp.assert(EXISTS(SELECT 1 FROM storage.objects WHERE name=path AND bucket_id='business-document-logos'),'Removal retains immutable asset');
 INSERT INTO orders(pharmacy_id,wholesaler_id,total_ghs) VALUES(a,b,42) RETURNING id INTO oid;
 SELECT identity INTO before_identity FROM document_identity_snapshots WHERE document_id=oid AND document_kind='pharmacy';
 PERFORM pg_temp.assert(before_identity->>'name'='Good Pharmacy','Snapshot uses registered buyer identity');
 SET LOCAL ROLE authenticated;
 PERFORM public.save_document_presentation(a,'New trading name',NULL,'#005588',true,true,'Changed');
 PERFORM pg_temp.assert((public.get_order_document_identity(oid,'pharmacy')->'issuer')=before_identity,'Branding changes preserve issued identity');
 PERFORM pg_temp.assert((public.get_order_document_identity(oid,'invoice')->'issuer'->>'name')='Alpha Wholesale','Invoice issuer is supplier');
 PERFORM pg_temp.assert((SELECT count(*) FROM document_branding_events WHERE business_id=a)>=2,'Audit records branding saves');
 RESET ROLE;
 INSERT INTO rfqs(pharmacy_id,title,created_by,status,submitted_at,enterprise) VALUES(a,'Snapshot test',uid,'open',now(),true) RETURNING id INTO rid;
 PERFORM pg_temp.assert(EXISTS(SELECT 1 FROM document_identity_snapshots WHERE document_kind='rfq' AND document_id=rid),'Submitted RFQ captures pharmacy branding');
 PERFORM pg_temp.assert(public.prepare_receipt_document_identity(oid,NULL)->>'name'='Alpha Wholesale','Receipt captures supplier identity');
 INSERT INTO orders(pharmacy_id,wholesaler_id,total_ghs,status) VALUES(a,b,42,'dispatched') RETURNING id INTO rid;
 PERFORM pg_temp.assert(EXISTS(SELECT 1 FROM document_identity_snapshots WHERE document_kind='delivery' AND document_id=rid),'Dispatch captures delivery issuer');
 INSERT INTO business_staff(business_id,user_id,role,status,joined_at) VALUES(a,staff_uid,'manager','active',now()) ON CONFLICT(business_id,user_id) DO UPDATE SET role='manager',status='active';
 PERFORM set_config('request.jwt.claim.sub',staff_uid::text,true);
 SET LOCAL ROLE authenticated;
 PERFORM public.save_document_presentation(a,NULL,NULL,'#115544',true,true,'Manager change');
 PERFORM pg_temp.assert(public.can_manage_document_branding(a),'Active manager can manage presentation');
 RESET ROLE;
 UPDATE business_staff SET role='assistant' WHERE business_id=a AND user_id=staff_uid;
 SET LOCAL ROLE authenticated;
 denied:=false;
 BEGIN PERFORM public.save_document_presentation(a,NULL,NULL,'#115544',true,true,'Forbidden'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Non-manager cannot save presentation');
 RESET ROLE;
 UPDATE business_staff SET role='manager',status='inactive' WHERE business_id=a AND user_id=staff_uid;
 SET LOCAL ROLE authenticated;
 PERFORM pg_temp.assert(NOT public.can_manage_document_branding(a),'Inactive manager denied');
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',(SELECT owner_id::text FROM businesses WHERE name='Pending Pharmacy'),true);
 SET LOCAL ROLE authenticated;
 denied:=false;
 BEGIN PERFORM public.get_order_document_identity(oid,'invoice'); EXCEPTION WHEN OTHERS THEN denied:=true; END;
 PERFORM pg_temp.assert(denied,'Unrelated user cannot retrieve snapshot');
 RESET ROLE;
END $$;
ROLLBACK;
